import test from 'node:test';
import assert from 'node:assert/strict';
import {createFoodWarningScene,foodWarningEvidence} from '../scripts/food-warning-native-fixture.mjs';
const create=Function('return ('+createFoodWarningScene.toString()+')')();
const project=Function('return ('+foodWarningEvidence.toString()+')')();

test('serialized warning native fixture prepares genuine harm, local attributed caution and interrupted exact reload (Node only)',{timeout:300000},async()=>{
  const scene=await create(new URL('../',import.meta.url),project),before=scene.project();
  const saved=scene.save(),raw=JSON.parse(saved.raw),actor=raw.agents.find(n=>n.id===saved.summary.actorId);
  const restored=saved.expectedRestored.agents.find(n=>n.id===actor.id);
  assert.deepEqual(scene.project(),before,'Serialization cannot advance original scene');
  assert.equal(saved.summary.missed.ok,false);
  const pair=saved.summary.choiceComparison;
  assert.equal(pair.sameFullStateAndRng,true);
  assert.ok(pair.latencySeconds>=0&&pair.latencySeconds<=30);
  assert.ok(pair.adverseEffectAt>=pair.firstSampleAt&&pair.adverseEffectAt-pair.firstSampleAt<=180);
  assert.deepEqual(pair.choices[1].action,{type:'sample',targetId:saved.summary.materialId});
  assert.notDeepEqual(pair.choices[0].action,pair.choices[1].action);
  assert.equal(restored.discovery.reports.filter(r=>r.warning).length,1);
  assert.deepEqual(restored.discovery.reports,actor.discovery.reports);
  assert.equal(restored.discovery.effects.length,0);
  assert.equal(restored.discovery.techniques.length,0);
  assert.equal(restored.active,null);
  assert.deepEqual(restored.physiology,actor.physiology);
  assert.deepEqual(restored.memory.experience.slice(0,actor.memory.experience.length),actor.memory.experience);
  assert.equal(restored.memory.experience.at(-1).details.result.code,'RESTART_INTERRUPTED');
  assert.equal(restored.social.heard.filter(m=>m.warning).length,1);
  assert.deepEqual(saved.expectedRestored.clocks,{environmentElapsed:raw.environment.elapsed,ecologyElapsed:raw.environment.ecology.elapsed,ecologyPending:raw.environment.ecology.pending});
  assert.match(saved.summary.fixtureDisclosure,/Not spontaneous encounter/);
});
